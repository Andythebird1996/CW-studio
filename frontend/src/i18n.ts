/** Replace `{name}` placeholders in a catalog string. */
export function tf(key: StringKey, lang: UILang, vars: Record<string, string | number>): string {
  let out: string = strings[key][lang];
  for (const [name, value] of Object.entries(vars)) {
    out = out.split(`{${name}}`).join(String(value));
  }
  return out;
}

/** Pick the singular or plural catalog string and substitute `{n}`. */
export function countPhrase(n: number, lang: UILang, one: StringKey, many: StringKey): string {
  return tf(n === 1 ? one : many, lang, { n });
}

export type StringKey = keyof typeof strings;

export function t(key: StringKey, lang: UILang): string {
  return strings[key][lang];
}

